#!/usr/bin/env python3
"""Generate a hardened OpenSSH sshd_config drop-in from a small JSON policy (stdlib only).

Crypto lists are intersected with what the local OpenSSH supports (`ssh -Q ...`) unless
--no-detect is given, so the output never references an algorithm the server rejects.

Usage:
  sshd_harden.py policy.json -o 00-cb-hardening.conf
  sshd_harden.py --example
Policy keys: allow_groups (required list), port, listen_addresses, trusted_user_ca_keys,
allow_tcp_forwarding, allow_agent_forwarding, banner, max_sessions.
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys

PREFERRED = {
    "KexAlgorithms": ["mlkem768x25519-sha256", "sntrup761x25519-sha512", "sntrup761x25519-sha512@openssh.com",
                      "curve25519-sha256", "curve25519-sha256@libssh.org"],
    "Ciphers": ["chacha20-poly1305@openssh.com", "aes256-gcm@openssh.com", "aes128-gcm@openssh.com",
                "aes256-ctr", "aes192-ctr", "aes128-ctr"],
    "MACs": ["hmac-sha2-512-etm@openssh.com", "hmac-sha2-256-etm@openssh.com", "umac-128-etm@openssh.com"],
    "HostKeyAlgorithms": ["ssh-ed25519", "ssh-ed25519-cert-v01@openssh.com", "rsa-sha2-512", "rsa-sha2-256",
                          "rsa-sha2-512-cert-v01@openssh.com", "rsa-sha2-256-cert-v01@openssh.com"],
    "PubkeyAcceptedAlgorithms": ["ssh-ed25519", "ssh-ed25519-cert-v01@openssh.com", "sk-ssh-ed25519@openssh.com",
                                 "sk-ssh-ed25519-cert-v01@openssh.com", "rsa-sha2-512", "rsa-sha2-256",
                                 "rsa-sha2-512-cert-v01@openssh.com", "rsa-sha2-256-cert-v01@openssh.com"],
}
QUERY = {"KexAlgorithms": "kex", "Ciphers": "cipher", "MACs": "mac",
         "HostKeyAlgorithms": "key-sig", "PubkeyAcceptedAlgorithms": "key-sig"}
NAME_RE = re.compile(r"^[a-z_][a-z0-9_.-]{0,31}$")
EXAMPLE = {"allow_groups": ["ssh-users", "admins"], "port": 22, "listen_addresses": [],
           "trusted_user_ca_keys": None, "allow_tcp_forwarding": False, "allow_agent_forwarding": False,
           "banner": "/etc/issue.net", "max_sessions": 4}


class PolicyError(ValueError):
    pass


def supported(kind):
    ssh = shutil.which("ssh")
    if not ssh:
        return None
    out = subprocess.run([ssh, "-Q", kind], capture_output=True, text=True)
    return set(out.stdout.split()) if out.returncode == 0 else None


def crypto(detect):
    result = {}
    for key, prefs in PREFERRED.items():
        available = supported(QUERY[key]) if detect else None
        chosen = [a for a in prefs if available is None or a in available]
        if not chosen:
            raise PolicyError(f"local OpenSSH supports none of the preferred {key}; upgrade OpenSSH")
        result[key] = chosen
    return result


def validate(policy):
    known = set(EXAMPLE)
    if set(policy) - known:
        raise PolicyError(f"unknown keys: {sorted(set(policy) - known)}")
    groups = policy.get("allow_groups")
    if not groups or not all(isinstance(g, str) and NAME_RE.fullmatch(g) for g in groups):
        raise PolicyError("allow_groups must be a non-empty list of valid group names (prevents lockout of "
                          "everyone and of unintended accounts)")
    port = policy.get("port", 22)
    if not isinstance(port, int) or not 1 <= port <= 65535:
        raise PolicyError("port must be 1-65535")
    for addr in policy.get("listen_addresses") or []:
        if not re.fullmatch(r"[0-9A-Fa-f:.\[\]]+", str(addr)):
            raise PolicyError(f"invalid listen address {addr!r}")
    for key in ("trusted_user_ca_keys", "banner"):
        value = policy.get(key)
        if value is not None and not str(value).startswith("/"):
            raise PolicyError(f"{key} must be an absolute path")
    sessions = policy.get("max_sessions", 4)
    if not isinstance(sessions, int) or not 1 <= sessions <= 64:
        raise PolicyError("max_sessions must be 1-64")
    return port, sessions


def render(policy, algos):
    port, sessions = validate(policy)
    yn = lambda flag: "yes" if flag else "no"  # noqa: E731
    lines = [
        "# Generated by Claude-Blue ssh-hardening-build. sshd uses the FIRST value it reads for most keywords,",
        "# so install this as /etc/ssh/sshd_config.d/00-cb-hardening.conf and make sure sshd_config includes",
        "# sshd_config.d/*.conf at its top (default on Debian/Ubuntu/Fedora/Arch).",
        f"Port {port}",
    ]
    lines += [f"ListenAddress {a}" for a in policy.get("listen_addresses") or []]
    lines += [
        "",
        "# Authentication: public keys (or user certificates) only",
        "PermitRootLogin no",
        "PubkeyAuthentication yes",
        "AuthenticationMethods publickey",
        "PasswordAuthentication no",
        "KbdInteractiveAuthentication no",
        "PermitEmptyPasswords no",
        "HostbasedAuthentication no",
        "IgnoreRhosts yes",
        f"AllowGroups {' '.join(policy['allow_groups'])}",
        "MaxAuthTries 3",
        "LoginGraceTime 30",
        "MaxStartups 10:30:60",
        f"MaxSessions {sessions}",
    ]
    if policy.get("trusted_user_ca_keys"):
        lines.append(f"TrustedUserCAKeys {policy['trusted_user_ca_keys']}")
    lines += [
        "",
        "# Features commonly abused for pivoting and persistence",
        f"AllowTcpForwarding {yn(policy.get('allow_tcp_forwarding'))}",
        f"AllowAgentForwarding {yn(policy.get('allow_agent_forwarding'))}",
        "AllowStreamLocalForwarding no",
        "X11Forwarding no",
        "PermitTunnel no",
        "GatewayPorts no",
        "PermitUserEnvironment no",
        "",
        "# Sessions and logging",
        "ClientAliveInterval 300",
        "ClientAliveCountMax 2",
        "LogLevel VERBOSE",
        "UseDNS no",
    ]
    if policy.get("banner"):
        lines.append(f"Banner {policy['banner']}")
    lines += ["", "# Cryptography (intersected with this OpenSSH build's supported algorithms)"]
    lines += [f"{key} {','.join(values)}" for key, values in algos.items()]
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("policy", nargs="?")
    ap.add_argument("-o", "--output")
    ap.add_argument("--no-detect", action="store_true", help="do not query local `ssh -Q`; use full preferred lists")
    ap.add_argument("--example", action="store_true")
    args = ap.parse_args(argv)
    if args.example:
        print(json.dumps(EXAMPLE, indent=2))
        return 0
    if not args.policy:
        ap.error("policy file required")
    try:
        text = render(json.load(open(args.policy, encoding="utf-8")), crypto(not args.no_detect))
    except (PolicyError, json.JSONDecodeError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2
    if args.output:
        with open(args.output, "w", encoding="utf-8") as handle:
            handle.write(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
